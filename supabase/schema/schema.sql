-- Content: anyone (signed in or not) may read; only the service role writes.
do $$
declare t text;
begin
  foreach t in array array['chapters','topics','theory_content','questions','question_options','formulas','flashcards'] loop
    execute format('drop policy if exists "content is public" on public.%I', t);
    execute format('create policy "content is public" on public.%I for select to anon, authenticated using (true)', t);
  end loop;
end $$;

-- Per-user tables: full access to your own rows only.
do $$
declare t text;
begin
  foreach t in array array['user_topic_progress','bookmarks','flashcard_reviews','quiz_results','question_attempts','study_activity','question_progress'] loop
    execute format('drop policy if exists "own rows" on public.%I', t);
    execute format('create policy "own rows" on public.%I for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id)', t);
  end loop;
end $$;

drop policy if exists "own profile" on public.profiles;
create policy "own profile" on public.profiles
  for all to authenticated using (auth.uid() = id) with check (auth.uid() = id);

