create extension if not exists "uuid-ossp";
create extension if not exists pgcrypto;   -- gen_random_uuid()

-- ---------------------------------------------------------------------
-- Content (public, read-only for the app; written by the import tools)
-- ---------------------------------------------------------------------
create table if not exists public.chapters (
  id          text primary key,
  title       text not null,
  description text not null,
  emoji       text not null,
  icon        text,
  "order"     integer not null
);

create table if not exists public.topics (
  id              text primary key,
  chapter_id      text not null references public.chapters(id),
  title           text not null,
  description     text not null,
  icon            text,
  "order"         integer not null,
  -- Chapter 1 restructure: NULL = top-level topic; otherwise the group it belongs to.
  parent_topic_id text references public.topics(id)
);
create index if not exists topics_parent_topic_id_idx on public.topics(parent_topic_id);
create index if not exists topics_chapter_id_idx on public.topics(chapter_id);

create table if not exists public.theory_content (
  topic_id text primary key references public.topics(id),
  concepts jsonb not null default '[]'::jsonb,
  formulas jsonb not null default '[]'::jsonb,
  notes    jsonb not null default '[]'::jsonb
);

create table if not exists public.questions (
  id            text primary key,
  chapter_id    text not null references public.chapters(id),
  topic_id      text not null references public.topics(id),
  question_text text not null,
  correct_index integer not null,
  explanation   text not null default '',
  difficulty    text not null default 'medium',
  formula       text,
  code_snippet  text,
  code_language text
);
create index if not exists questions_chapter_id_idx on public.questions(chapter_id);
create index if not exists questions_topic_id_idx on public.questions(topic_id);

create table if not exists public.question_options (
  id           bigint generated by default as identity primary key,
  question_id  text not null references public.questions(id) on delete cascade,
  option_index integer not null,
  option_text  text not null,
  unique (question_id, option_index)
);

create table if not exists public.formulas (
  id          text primary key,
  chapter_id  text not null references public.chapters(id),
  topic_id    text not null references public.topics(id),
  title       text not null,
  description text not null default '',
  latex       text,
  plain_text  text not null,
  is_code     boolean default false
);
create index if not exists formulas_chapter_id_idx on public.formulas(chapter_id);

create table if not exists public.flashcards (
  id         text primary key,
  chapter_id text not null references public.chapters(id),
  topic_id   text not null references public.topics(id),
  front      text not null,
  back       text not null,
  difficulty text not null default 'medium'
);
create index if not exists flashcards_chapter_id_idx on public.flashcards(chapter_id);

-- ---------------------------------------------------------------------
-- Per-user data (row-level security: users see and change only their own rows)
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id                    uuid primary key references auth.users(id) on delete cascade,
  theme_mode            text default 'system',
  preferred_quiz_length integer default 10,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

create table if not exists public.user_topic_progress (
  user_id         uuid not null references auth.users(id) on delete cascade,
  topic_id        text not null references public.topics(id),
  completed       boolean not null default false,
  completion_pct  double precision not null default 0,
  last_studied_at timestamptz not null default now(),
  primary key (user_id, topic_id)
);

create table if not exists public.bookmarks (
  user_id    uuid not null references auth.users(id) on delete cascade,
  item_type  text not null,            -- 'question' | 'formula' | 'topic'
  item_id    text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, item_type, item_id)
);

create table if not exists public.flashcard_reviews (
  user_id          uuid not null references auth.users(id) on delete cascade,
  card_id          text not null references public.flashcards(id) on delete cascade,
  ease             double precision not null default 2.5,
  interval_days    integer not null default 1,
  due_date         timestamptz not null default now(),
  review_count     integer not null default 0,
  last_reviewed_at timestamptz not null default now(),
  primary key (user_id, card_id)
);

create table if not exists public.quiz_results (
  id             uuid primary key default gen_random_uuid(),
  user_id        uuid not null references auth.users(id) on delete cascade,
  mode           text not null,        -- practice | timed | mock | bookmarked | fullExam
  chapter_id     text references public.chapters(id),
  score_achieved integer not null,
  score_total    integer not null,
  percentage     double precision not null,
  time_seconds   integer not null,
  taken_at       timestamptz not null default now()
);
create index if not exists quiz_results_user_id_idx on public.quiz_results(user_id, taken_at desc);

create table if not exists public.question_attempts (
  id             uuid primary key default gen_random_uuid(),
  result_id      uuid not null references public.quiz_results(id) on delete cascade,
  user_id        uuid not null references auth.users(id) on delete cascade,
  question_id    text not null references public.questions(id),
  chapter_id     text references public.chapters(id),
  topic_id       text references public.topics(id),
  selected_index integer not null,
  is_correct     boolean not null,
  time_ms        integer not null
);
create index if not exists question_attempts_user_id_idx on public.question_attempts(user_id);

create table if not exists public.study_activity (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references auth.users(id) on delete cascade,
  activity_date date not null,
  source        text not null default 'app',
  created_at    timestamptz not null default now(),
  -- the app upserts on (user_id, activity_date)
  unique (user_id, activity_date)
);

-- Latest Practice-mode answer per user per question (see
-- migrations/20260927_question_progress.sql). No FK to questions on purpose.
create table if not exists public.question_progress (
  user_id     uuid not null references auth.users(id) on delete cascade,
  question_id text not null,
  is_correct  boolean not null,
  answered_at timestamptz not null default now(),
  primary key (user_id, question_id)
