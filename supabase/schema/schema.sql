-- Saves a finished quiz and its per-question attempts in one transaction and
-- logs the day's study activity for the streak. Called by the app as
--   rpc('save_quiz_result', {p_mode, p_chapter_id, p_score_achieved,
--       p_score_total, p_percentage, p_time_seconds, p_attempts: [...]})
-- p_attempts items: {question_id, chapter_id, topic_id, selected_index, is_correct, time_ms}
create or replace function public.save_quiz_result(
  p_mode           text,
  p_chapter_id     text,
  p_score_achieved integer,
  p_score_total    integer,
  p_percentage     double precision,
  p_time_seconds   integer,
  p_attempts       jsonb
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user   uuid := auth.uid();
  v_result uuid;
begin
  if v_user is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;

  insert into public.quiz_results (user_id, mode, chapter_id, score_achieved, score_total, percentage, time_seconds)
  values (v_user, p_mode, nullif(p_chapter_id, ''), p_score_achieved, p_score_total, p_percentage, p_time_seconds)
  returning id into v_result;

  insert into public.question_attempts (result_id, user_id, question_id, chapter_id, topic_id, selected_index, is_correct, time_ms)
  select v_result, v_user,
         a->>'question_id',
         nullif(a->>'chapter_id', ''),
         nullif(a->>'topic_id', ''),
         coalesce((a->>'selected_index')::integer, -1),
         coalesce((a->>'is_correct')::boolean, false),
         coalesce((a->>'time_ms')::integer, 0)
  from jsonb_array_elements(coalesce(p_attempts, '[]'::jsonb)) as a
  where a ? 'question_id';

  insert into public.study_activity (user_id, activity_date, source)
  values (v_user, current_date, 'quiz')
  on conflict (user_id, activity_date) do nothing;

  return v_result;
end;
$$;
revoke all on function public.save_quiz_result(text, text, integer, integer, double precision, integer, jsonb) from public;
grant execute on function public.save_quiz_result(text, text, integer, integer, double precision, integer, jsonb) to authenticated, service_role;

-- Maintenance helper: turns RLS on for every table in public (no-op when already on).
create or replace function public.rls_auto_enable()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end;
$$;
revoke all on function public.rls_auto_enable() from public;
grant execute on function public.rls_auto_enable() to service_role;

